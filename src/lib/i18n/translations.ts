export function pickLocalized(
  locale: Locale,
  fr: string | null | undefined,
  ar: string | null | undefined,
): string {
  if (locale === "ar") {
    return ar?.trim() ? ar : (fr ?? "");
  }
  return fr?.trim() ? fr : (ar ?? "");
}

